def estimate_mutation_rates(variants_df, h37Rv_seq):
    
    # Count substitutions
    sub_counts = Counter(zip(variants_df["REF"], variants_df["ALT"]))

    # Count genome-wide base composition
    genome_base_counts = Counter(h37Rv_seq.seq)

    # Compute per-base mutation rates
    mu = {}
    for ref in "ACGT":
        ref_total = genome_base_counts.get(ref, 0)
        for alt in "ACGT":
            if ref != alt:
                mu[(ref, alt)] = sub_counts.get((ref, alt), 0) / ref_total

    return mu



def expected_mutations_per_gene(regions_lst, h37Rv_seq, mu):
    
    expected = {}
    gene_lengths = {}

    for region in regions_lst:
        
        if region in h37Rv_genes.Symbol.values:
            start = h37Rv_genes.query("Symbol==@region").Start.values[0]
            end = h37Rv_genes.query("Symbol==@region").End.values[0]
            
        elif 'NC' in region:
            start = h37Rv_coords.query("region==@region").pos.min()
            end = h37Rv_coords.query("region==@region").pos.max()
            
        else:
            raise ValueError(f"{region} not found!")
            
        seq = str(h37Rv_seq.seq[start-1:end]).upper()

        counts = Counter(seq)

        E = 0.0
        for ref in "ACGT":
            for alt in "ACGT":
                if ref != alt:
                    E += counts.get(ref, 0) * mu[(ref, alt)]

        expected[region] = E
        gene_lengths[region] = [start, end, len(seq)]

    return pd.Series(expected, name="Expected"), pd.DataFrame(gene_lengths, index=['Start', 'End', 'Length']).T


# codon-aware helper functions
standard_table = CodonTable.unambiguous_dna_by_name["Standard"]
stop_codons = set(standard_table.stop_codons)

def mutate_codon(codon, pos, alt):
    codon_list = list(codon)
    codon_list[pos] = alt
    return "".join(codon_list)

def classify_mutation(codon, new_codon):
    
    # pass in a codon and return the amino acid. If the codon is not found, return * because stop codons are not in the dictionary generated by the standard table
    aa1 = standard_table.forward_table.get(codon, "*")
    aa2 = standard_table.forward_table.get(new_codon, "*")
    
    # track mutations to nonsyn (aa2) separately because they are strongly selected against in the MTBC
    if aa1 == aa2:
        return "synonymous"
    else:
        if aa2 != '*':
            return "nonsynonymous"
        else:
            return "nonsense"


def expected_mutations_per_region(regions_lst, h37Rv_seq, mu, h37Rv_genes):
    
    expected = {}
    gene_lengths = {}

    for region in regions_lst:
        
        if region in h37Rv_genes.Symbol.values:
            row = h37Rv_genes.query("Symbol==@region").iloc[0]
            start, end, sense = row.Start, row.End, row.Strand
            is_coding = True
            
        elif 'NC_' in region:
            start = h37Rv_coords.query("region==@region").pos.min()
            end = h37Rv_coords.query("region==@region").pos.max()
            is_coding = False
            sense = '+' # default to positive sense for intergenic regions, tho it doesn't matter
            
        else:
            raise ValueError(f"{region} not found!")
            
        seq = str(h37Rv_seq.seq[start-1:end]).upper()
        
        if sense != '+':
            seq = str(Seq.Seq(seq).reverse_complement())
        
        # E_syn, E_nonsyn, E_nonsense, E_total = 0.0, 0.0, 0.0, 0.0
        E_syn, E_nonsyn, E_total = 0.0, 0.0, 0.0

        # Only apply codon model to coding regions
        if is_coding:

            for i in range(0, len(seq), 3):
                codon = seq[i:i+3]
                                
                # skip ambiguous codons
                if any(b not in "ACGT" for b in codon):
                    continue

                for pos in range(3):
                    ref = codon[pos]

                    for alt in "ACGT":
                        if alt == ref:
                            continue

                        new_codon = mutate_codon(codon, pos, alt)
                        mut_type = classify_mutation(codon, new_codon)
                        
                        if mut_type == "synonymous":
                            E_syn += mu[(ref, alt)]
                        else:
                            E_nonsyn += mu[(ref, alt)]
                        # elif mut_type == "nonsynonymous":
                        #     E_nonsyn += mu[(ref, alt)]
                        # else:
                        #     E_nonsense += mu[(ref, alt)]
                        
                        E_total += mu[(ref, alt)]

        else:
            # use the original nucleotide model for intergenic regions because there are no syn or nonsyn mutations
            counts = Counter(seq)
            for ref in "ACGT":
                for alt in "ACGT":
                    if ref != alt:
                        E_total += counts.get(ref, 0) * mu[(ref, alt)]

        expected[region] = {
            "E_syn": E_syn,
            "E_nonsyn": E_nonsyn,
            # "E_nonsense": E_nonsense,
            "E_total": E_total
        }
        
        gene_lengths[region] = [start, end, len(seq)]

    return pd.DataFrame(expected).T, pd.DataFrame(gene_lengths, index=['Start','End','Length']).T


def count_observed_mutations(variants_df, h37Rv_seq, h37Rv_genes):
    
    observed = {}
    
    regions_lst = np.concatenate([
        variants_df.query("~Region.str.contains('NC')").GENE.unique(),
        variants_df.query("Region.str.contains('NC')").Region.unique()
    ])
    
    for region in regions_lst:
        region_df = variants_df[(variants_df.GENE==region) | (variants_df.Region==region)]
        row = h37Rv_genes.query("Symbol==@region") if region in h37Rv_genes.Symbol.values else None

        if row is not None and len(row) > 0:
            # coding
            row = h37Rv_genes.query("Symbol==@region").iloc[0]
            start, end, sense = row.Start, row.End, row.Strand
            
            seq = str(h37Rv_seq.seq[start-1:end]).upper()

            # O_syn, O_nonsyn, O_nonsense = 0, 0, 0
            O_syn, O_nonsyn = 0, 0
            L = len(seq) - (len(seq)%3)
            seq = seq[:L]

            for idx, row_var in region_df.iterrows():

                if sense == '+':
                    pos = row_var.POS - start  # 0-based in gene
                    codon_start = (pos // 3) * 3
                    codon_pos = pos % 3
                    codon = seq[codon_start:codon_start+3]
                else:
                    pos = end - row_var.POS  # 0-based in gene
                    codon_start = (pos // 3) * 3
                    codon_pos = pos % 3
                    codon = Seq.Seq(seq).reverse_complement()[codon_start:codon_start+3]

                if len(codon) != 3 or any(b not in "ACGT" for b in codon):
                    raise ValueError(f"Incorrect codon at {pos} in {region}")

                ref = row_var.REF
                alt = row_var.ALT

                # in the variant table, REF and ALT are always in positive sense
                # so if the gene is negative sense, then alt needs to be reverse complemented. 
                # codon is already reverse complemented if needed, and codon_pos is the index within the codon
                if sense == '+':
                    new_codon = codon[:codon_pos] + alt + codon[codon_pos+1:]
                else:
                    new_codon = codon[:codon_pos] + str(Seq.Seq(alt).reverse_complement()) + codon[codon_pos+1:]

                mut_type = classify_mutation(codon, new_codon)
                
                if mut_type == "synonymous":
                    O_syn += 1
                else:
                    O_nonsyn += 1
                # elif mut_type == "nonsynonymous":
                #     O_nonsyn += 1
                # else:
                #     O_nonsense += 1
            
            observed[region] = {
                "O_syn": O_syn,
                "O_nonsyn": O_nonsyn,
                # "O_nonsense": O_nonsense,
                "O_total": len(region_df)
            }
        else:
            # intergenic
            observed[region] = {"O_total": len(region_df)}
    
    return pd.DataFrame(observed).T.fillna(0)


def poisson_enrichment_test(observed, expected):
    
    df = pd.concat([observed, expected], axis=1).fillna(0)

    df["Fold_Enrichment"] = df["Observed"] / df["Expected"].replace(0, np.nan)

    # One-sided test: enrichment
    df["Enrich_pval"] = st.poisson.sf(df["Observed"] - 1, df["Expected"])

    return df.sort_values("Twosided_pval")


