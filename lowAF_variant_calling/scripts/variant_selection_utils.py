def poisson_enrichment_test(observed_df, expected_df):
    """
    Poisson-based enrichment test for coding and intergenic regions.
    Returns a consistent DataFrame with columns:
    syn_pval, syn_fold, nonsyn_pval, nonsyn_fold, nonsense_pval, nonsense_fold,
    total_pval, total_fold
    """
    results = {}

    for region in observed_df.index:
        obs = observed_df.loc[region]
        exp = expected_df.loc[region]

        region_results = {}

        # intergenic region prefix
        if region[:3] == 'NC_':
            
            O_total = obs["O_total"]
            E_total = exp["E_total"]

            # coding columns set to NaN
            region_results["syn_pval"] = np.nan
            region_results["syn_fold"] = np.nan
            region_results["nonsyn_pval"] = np.nan
            region_results["nonsyn_fold"] = np.nan
            # region_results["nonsense_pval"] = np.nan
            # region_results["nonsense_fold"] = np.nan

            # intergenic enrichment
            region_results["total_pval"] = st.poisson.sf(O_total - 1, E_total)
            region_results["total_fold"] = O_total / (E_total + 1e-8)

        else:
            total_O, total_E = 0, 0
            
            for mut_type in ["syn", "nonsyn"]:#, "nonsense"]:
                O = obs[f"O_{mut_type}"]
                E = exp[f"E_{mut_type}"]

                if E == 0:
                    p_val = np.nan
                    fold = np.nan
                else:
                    p_val = st.poisson.sf(O - 1, E)
                    fold = O / E

                region_results[f"{mut_type}_pval"] = p_val
                region_results[f"{mut_type}_fold"] = fold

                total_O += O
                total_E += E

            # total enrichment across all coding mutations
            region_results["total_pval"] = st.poisson.sf(total_O - 1, total_E)
            region_results["total_fold"] = total_O / (total_E + 1e-8)

        results[region] = region_results

    combined_results = pd.DataFrame(results).T.merge(observed_df, left_index=True, right_index=True).merge(expected_df, left_index=True, right_index=True)

    for col in combined_results.columns[combined_results.columns.str.endswith('_pval')]:
        
        # exclude the intergenic regions when correcting syn/nonsyn/nonsense p-values because they don't have them
        combined_results[f'{col}_Bonferroni'] = combined_results[col] * len(combined_results.dropna(subset=col))
        combined_results.loc[combined_results[f'{col}_Bonferroni'] > 1, f'{col}_Bonferroni'] = 1
        
    return combined_results



def perform_codon_aware_enrichment_test(variants_df, h37Rv_seq=h37Rv_seq, h37Rv_genes=h37Rv_genes, h37Rv_coords=h37Rv_coords, keep_lineages=None, neutral_bg_only=False):
    
    if keep_lineages is not None:
        variants_df = variants_df.query("Lineage in @keep_lineages")
    
    regions_lst = np.concatenate([
        variants_df.query("~Region.str.contains('NC')").GENE.unique(),
        variants_df.query("Region.str.contains('NC')").Region.unique()
    ])
    
    # because of variants occurring in overlapping genes, there are duplicate positions. This is needed for accurately counting mutations, 
    # but it will inflate mu because of double counting, so drop duplicates before estimating mu
    # if use only silent and intergenic variants to estimate mu
    if neutral_bg_only:
        mu = estimate_mutation_rates(
            variants_df.query("Variant_Type in ['Silent', 'Intergenic']").drop_duplicates(subset=['SampleID','POS','REF','ALT']),
            h37Rv_seq
        )
    else:
        mu = estimate_mutation_rates(
            variants_df.drop_duplicates(subset=['SampleID','POS','REF','ALT']),
            h37Rv_seq
        )
    
    expected_df, gene_lengths_df = expected_mutations_per_region(
        regions_lst, h37Rv_seq, mu, h37Rv_genes
    )
    
    # deduplicate variants on the same haplotype and codon. If they occur on the same codon, they are a single instance of a mutation
    variants_df_for_counting_obs = pd.concat([variants_df.query("Variant_Type != 'Intergenic'").drop_duplicates(['SampleID', 'GENE', 'HGVS_C']),
                                              variants_df.query("Variant_Type == 'Intergenic'")
                                             ]).sort_values(['pid', 'SampleID', 'POS']).reset_index(drop=True)

    observed_df = count_observed_mutations(variants_df_for_counting_obs, h37Rv_seq, h37Rv_genes)
    
    results_df = poisson_enrichment_test(observed_df, expected_df)
    
    return results_df.merge(gene_lengths_df, left_index=True, right_index=True), mu